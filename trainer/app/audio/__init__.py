"""共享音频内核。

语音变声（RVC）与歌声转换（DDSP-SVC）在技术上有一大段是重合的：读音频、
切分、提 F0、提内容特征、分离人声与伴奏、混音、缓存中间结果。
这些如果各写一份，就会出现「同一个功能在两个板块里行为不一致」——
比如 RVC 能读的格式 DDSP 读不了，或者两个板块各自缓存了一份同样的分离结果。

所以重合部分全部下沉到这里，两个板块只保留各自模型专有的部分。

    io        读写 / 重采样 / 内容指纹
    cache     中间结果缓存（分离与特征，按内容指纹 + 参数命中）
    uvr5      UVR5 人声/伴奏分离（直连官方算法）
    mixer     混音：增益 / 延迟对齐 / 淡入淡出

F0 与内容特征（`f0.py` / `features.py`）由歌声转换板块引入后同样落在这里，
语音变声板块直接复用 —— 这两个模型用的是同一批 HuBERT / ContentVec 权重。
"""

